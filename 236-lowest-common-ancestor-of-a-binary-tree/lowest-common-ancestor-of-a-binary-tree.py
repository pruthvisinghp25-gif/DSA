class Solution(object):
    def lowestCommonAncestor(self, root, p, q):
        if root is None:
            return None
        left = self.lowestCommonAncestor(root.left, p, q)
        right = self.lowestCommonAncestor(root.right, p, q)

        if left and right:
            return root

        if root == p or root == q:
            return root

        return right if not left else left
             

        